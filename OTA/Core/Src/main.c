/* Queries the server's current ETag over the W5500 and, if it differs
 * from what's installed, hands the update off to the bootloader: write
 * "update pending" + the new ETag to the shared control block, then
 * reset. The bootloader (not this app) does the actual download/flash/
 * verify on the next boot. */
static void CheckForUpdate(void)
{
  ota_ctrl_t ctrl;
  OTA_Ctrl_Load(&ctrl);

  const uint8_t server_ip[4] = SERVER_IP;
  W5500_Init();
  if (!W5500_LinkUp()) return; /* cable unplugged / no link this cycle, just retry next poll */

  http_response_t resp;
  if (http_head(server_ip, SERVER_PORT, SERVER_HOST, FIRMWARE_PATH, &resp) != 0) return;
  if (resp.status_code != 200 || resp.etag[0] == 0) return;

  if (strcmp(resp.etag, ctrl.installed_etag) == 0) return; /* already running this version */

  ctrl.update_pending = 1;
  strncpy(ctrl.pending_etag, resp.etag, sizeof(ctrl.pending_etag) - 1);
  ctrl.pending_etag[sizeof(ctrl.pending_etag) - 1] = 0;
  OTA_Ctrl_Save(&ctrl);

  NVIC_SystemReset();
}
